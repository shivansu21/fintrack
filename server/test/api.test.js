import test,{before,after} from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import {MongoMemoryServer} from 'mongodb-memory-server';
import request from 'supertest';
import {createApp} from '../src/app.js';
import {User,Transaction,Budget,Recurring} from '../src/models.js';
import {processRecurring} from '../src/recurring.js';
import {today} from '../src/domain.js';
import {createHash} from 'node:crypto';
let mongo,app,a,b;
before(async()=>{process.env.JWT_SECRET='test-only-secret-long-enough-for-jwt-tests';process.env.APP_ORIGIN='http://localhost:5173';process.env.NODE_ENV='test';mongo=await MongoMemoryServer.create();await mongoose.connect(mongo.getUri());await Promise.all([User.init(),Transaction.init(),Budget.init(),Recurring.init()]);app=createApp();a=request.agent(app);b=request.agent(app);});
after(async()=>{await mongoose.disconnect();await mongo?.stop()});
const post=(agent,url,data)=>agent.post(url).set('X-FinTrack','1').send(data);
const record={type:'expense',amount:12.34,category:'Food',description:'Lunch, "thali"',paymentMethod:'UPI',date:'2026-01-05'};
test('full API workflow, isolation, budgets, filters, reset and recurring',async()=>{
 assert.equal((await request(app).get('/api/transactions')).status,401);
 assert.equal((await post(a,'/api/auth/register',{name:'Test User',email:'a@example.com',password:'password123'})).status,201);
 assert.equal((await post(b,'/api/auth/register',{name:'Other User',email:'b@example.com',password:'password123'})).status,201);
 assert.equal((await post(a,'/api/transactions',{...record,amount:-1})).status,400);
 assert.equal((await a.post('/api/transactions').send(record)).status,403);
 assert.equal((await post(a,'/api/transactions',record).set('Origin','https://evil.example')).status,403);
 const created=await post(a,'/api/transactions',record);assert.equal(created.status,201);const id=created.body._id;
 assert.equal((await b.get('/api/transactions')).body.total,0);
 assert.equal((await b.put('/api/transactions/'+id).set('X-FinTrack','1').send(record)).status,404);
 assert.equal((await b.delete('/api/transactions/'+id).set('X-FinTrack','1')).status,404);
 assert.equal((await a.put('/api/transactions/'+id).set('X-FinTrack','1').send({...record,amount:20})).status,200);
 await post(a,'/api/transactions',{...record,type:'income',amount:100,category:'Salary'});
 const s=(await a.get('/api/summary?month=2026-01')).body;assert.equal(s.income,100);assert.equal(s.expense,20);assert.equal(s.balance,80);
 assert.equal((await a.put('/api/budgets').set('X-FinTrack','1').send({month:'2026-01',category:'Food',amount:30})).status,200);
 assert.equal((await a.get('/api/budgets?month=2026-01')).body[0].spent,20);
 assert.equal((await a.get('/api/transactions?type=expense&min=15&max=25&q=thali')).body.total,1);
 assert.equal((await a.get('/api/transactions?q=%5B')).status,200);
 assert.equal((await a.get('/api/transactions?from=2026-02-02&to=2026-01-01')).status,400);
 assert.equal((await a.get('/api/transactions/export?min=50&max=1')).status,400);
 const csv=await a.get('/api/transactions/export?type=expense');assert.equal(csv.status,200);assert.match(csv.text,/Lunch, ""thali""/);assert.doesNotMatch(csv.text,/Salary/);
 for(let i=0;i<15;i++)await post(a,'/api/transactions',{...record,amount:1});
 const p1=(await a.get('/api/transactions')).body,p2=(await a.get('/api/transactions?page=2')).body;assert.equal(p1.rows.length,15);assert.equal(p2.rows.length,2);assert.equal(new Set([...p1.rows,...p2.rows].map(t=>t._id)).size,17);
 const owner=await User.findOne({email:'a@example.com'});const rule=await Recurring.create({userId:owner._id,type:'expense',amountPaise:100,category:'Bills',description:'Recurring test',paymentMethod:'UPI',nextDate:today(),frequency:'monthly',dayOfMonth:Number(today().slice(8))});
 await Promise.all([processRecurring(owner._id),processRecurring(owner._id)]);assert.equal(await Transaction.countDocuments({recurrenceKey:{$regex:String(rule._id)}}),1);
 assert.equal((await a.delete('/api/recurring/'+rule._id).set('X-FinTrack','1')).status,200);
 assert.equal(await Transaction.countDocuments({recurrenceKey:{$regex:String(rule._id)}}),1);
 assert.equal((await post(a,'/api/demo-data',{})).status,409);
 assert.equal((await post(b,'/api/demo-data',{})).status,201);
 const token='a'.repeat(64);await User.updateOne({_id:owner._id},{$set:{resetHash:createHash('sha256').update(token).digest('hex'),resetExpires:new Date(Date.now()+100000)}});
 assert.equal((await post(a,'/api/auth/reset-password',{token,password:'newpassword123'})).status,200);
 assert.equal((await a.get('/api/me')).status,401);
 assert.equal((await post(a,'/api/auth/reset-password',{token,password:'anotherpassword'})).status,400);
 assert.equal((await post(a,'/api/auth/login',{email:'a@example.com',password:'newpassword123'})).status,200);
 assert.equal((await a.delete('/api/transactions/'+id).set('X-FinTrack','1')).status,200);
 assert.equal((await post(a,'/api/auth/logout',{})).status,200);
 assert.equal((await a.get('/api/me')).status,401);
});
